import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(__dirname, '../src/api/generated/openapi-types.ts');
const baselinePath = resolve(__dirname, '../../backend/openapi-baseline.json');
const defaultUrl = process.env.OPENAPI_URL || 'http://localhost:8080/v3/api-docs';
const args = new Set(process.argv.slice(2));
const checkOnly = args.has('--check');
const urlArg = process.argv.find((arg) => arg.startsWith('--url='));
const openapiUrl = urlArg ? urlArg.slice('--url='.length) : defaultUrl;

async function loadOpenApi() {
  if (process.env.OPENAPI_USE_BASELINE === 'true') {
    return loadBaseline();
  }
  try {
    const response = await fetch(openapiUrl, { signal: AbortSignal.timeout(5000) });
    if (response.ok) {
      return await response.json();
    }
    console.warn(`Backend not reachable (${response.status}), falling back to baseline...`);
  } catch {
    console.warn('Backend not reachable, falling back to baseline...');
  }
  return loadBaseline();
}

function loadBaseline() {
  if (!existsSync(baselinePath)) {
    throw new Error(
      `Baseline file not found at ${baselinePath}. ` +
      'Start the backend or set OPENAPI_URL to a running instance, ' +
      'or set OPENAPI_USE_BASELINE=true if the baseline file exists.'
    );
  }
  const raw = readFile(baselinePath, 'utf8');
  return raw.then(JSON.parse);
}

const openapi = await loadOpenApi();
const schemas = openapi.components?.schemas || {};
const generated = renderTypes(schemas);

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8');
  if (current !== generated) {
    throw new Error('Generated OpenAPI types are out of date. Run npm run contracts:generate.');
  }
} else {
  await writeFile(outputPath, generated);
}

function renderTypes(schemasByName) {
  const lines = [
    '/* eslint-disable */',
    '// Generated by scripts/generate-openapi-types.mjs from the backend OpenAPI contract.',
    '// Do not edit manually.',
    '',
    'export namespace ApiSchemas {',
  ];

  for (const [name, schema] of Object.entries(schemasByName).sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(renderSchemaInterface(name, schema));
  }

  lines.push('}', '');
  return lines.join('\n');
}

function renderSchemaInterface(name, schema) {
  if (schema.type !== 'object' && !schema.properties) {
    return `  export type ${safeTypeName(name)} = ${toTsType(schema)};\n`;
  }

  const required = new Set(schema.required || []);
  const lines = [`  export interface ${safeTypeName(name)} {`];
  for (const [propertyName, propertySchema] of Object.entries(schema.properties || {})) {
    const optional = required.has(propertyName) ? '' : '?';
    lines.push(`    ${safePropertyName(propertyName)}${optional}: ${toTsType(propertySchema)};`);
  }
  lines.push('  }', '');
  return lines.join('\n');
}

function toTsType(schema) {
  if (!schema) {
    return 'unknown';
  }
  if (schema.$ref) {
    return `ApiSchemas.${safeTypeName(schema.$ref.split('/').pop())}`;
  }
  if (schema.oneOf || schema.anyOf) {
    return (schema.oneOf || schema.anyOf).map(toTsType).join(' | ');
  }
  if (schema.allOf) {
    return schema.allOf.map(toTsType).join(' & ');
  }
  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  }

  const nullable = schema.nullable ? ' | null' : '';
  switch (schema.type) {
    case 'array':
      return `${toTsType(schema.items)}[]${nullable}`;
    case 'integer':
    case 'number':
      return `number${nullable}`;
    case 'boolean':
      return `boolean${nullable}`;
    case 'string':
      return `string${nullable}`;
    case 'object':
      if (schema.additionalProperties) {
        return `Record<string, ${toTsType(schema.additionalProperties)}>${nullable}`;
      }
      return `Record<string, unknown>${nullable}`;
    default:
      return `unknown${nullable}`;
  }
}

function safeTypeName(name) {
  return String(name || 'Unknown').replace(/[^a-zA-Z0-9_$]/g, '_');
}

function safePropertyName(name) {
  return /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}
